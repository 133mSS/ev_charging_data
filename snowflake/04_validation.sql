-- Run after 02_warehouse.sql and (for Q5) 03_power_marts.sql.
USE DATABASE JPL_ANALYTICS;
USE WAREHOUSE JPL_ETL_WH;

-- 1. Reconcile migrated source row counts.
SELECT 'API_SESSIONS' AS DATASET, COUNT(*) AS ROW_COUNT
FROM WAREHOUSE.FACT_CHARGING_SESSIONS
UNION ALL
SELECT 'USER_INPUTS', COUNT(*) FROM WAREHOUSE.FACT_USER_REQUESTS
UNION ALL
SELECT 'STATIC_ALL', COUNT(*) FROM WAREHOUSE.FACT_STATIC_MEASUREMENTS
UNION ALL
SELECT 'STATIC_MATCHED', COUNT(*) FROM WAREHOUSE.FACT_STATIC_MEASUREMENTS WHERE MATCH_STATUS = 'MATCHED'
UNION ALL
SELECT 'STATIC_ONLY', COUNT(*) FROM WAREHOUSE.FACT_STATIC_MEASUREMENTS WHERE MATCH_STATUS = 'STATIC_ONLY';

-- 2. Q1: charging demand by weekday and local hour.
SELECT DAY_OF_WEEK, LOCAL_HOUR, COUNT(*) AS SESSION_COUNT,
       SUM(ENERGY_KWH) AS ENERGY_KWH
FROM WAREHOUSE.FACT_CHARGING_SESSIONS
GROUP BY DAY_OF_WEEK, LOCAL_HOUR
ORDER BY DAY_OF_WEEK, LOCAL_HOUR;

-- 3. Q2: EVSE usage ranking.
SELECT * FROM ANALYTICS.V_Q2_STATION_USAGE
ORDER BY TOTAL_ENERGY_KWH DESC;

-- 4. Q3: connection duration and post-last-positive-current interval.
SELECT
    COUNT(*) AS VALID_SESSIONS,
    MEDIAN(POST_LAST_CURRENT_MINUTES) AS MEDIAN_POST_CURRENT_MINUTES,
    PERCENTILE_CONT(0.95) WITHIN GROUP (ORDER BY POST_LAST_CURRENT_MINUTES) AS P95_POST_CURRENT_MINUTES
FROM MART.SESSION_POST_CURRENT;

-- 5. Q4: latest request vs delivered energy; latest event is selected BEFORE filtering kWh.
WITH LATEST AS (
    SELECT *
    FROM WAREHOUSE.FACT_USER_REQUESTS
    QUALIFY ROW_NUMBER() OVER (
        PARTITION BY SESSION_ID ORDER BY MODIFIED_AT DESC NULLS LAST, INPUT_ID DESC
    ) = 1
)
SELECT
       COUNT(*) AS Q4_OUTPUT_ROWS,
       COUNT(DISTINCT F.SESSION_ID) AS DISTINCT_SESSIONS_IN_Q4,
       COUNT(*) - COUNT(DISTINCT F.SESSION_ID) AS DUPLICATE_SESSION_ROWS,
       MEDIAN(100.0 * F.ENERGY_KWH / NULLIF(L.KWH_REQUESTED, 0))
           AS MEDIAN_DELIVERED_VS_REQUESTED_PCT
FROM WAREHOUSE.FACT_CHARGING_SESSIONS F
JOIN LATEST L USING (SESSION_ID)
WHERE L.KWH_REQUESTED > 0;

-- 6. Q5: Power and temporal observation coverage.
SELECT COUNT(*) AS EXPECTED_UTC_HOURS,
       COUNT_IF(SITE_HOUR_HAS_ANY_OBSERVATION) AS HOURS_WITH_OBSERVATION,
       COUNT_IF(NOT SITE_HOUR_HAS_ANY_OBSERVATION) AS HOURS_WITHOUT_OBSERVATION
FROM MART.POWER_SITE_HOUR;

-- Monthly calendar-hour coverage uses the fixed 50-station population.
-- A station-month with no Static observations contributes 0% coverage, not a missing row.
WITH MONTHS AS (
    SELECT TO_DATE('2020-07-01') AS LOCAL_MONTH
    UNION ALL SELECT TO_DATE('2020-08-01')
    UNION ALL SELECT TO_DATE('2020-09-01')
    UNION ALL SELECT TO_DATE('2020-10-01')
    UNION ALL SELECT TO_DATE('2020-11-01')
),
STATIONS AS (
    SELECT DISTINCT STATION_ID
    FROM MART.POWER_STATION_HOUR
),
STATION_MONTH_GRID AS (
    SELECT
        S.STATION_ID,
        M.LOCAL_MONTH,
        COALESCE(P.OBSERVED_UTC_HOURS, 0) AS OBSERVED_UTC_HOURS,
        COALESCE(P.CALENDAR_HOUR_OBSERVATION_PCT, 0) AS CALENDAR_HOUR_OBSERVATION_PCT
    FROM STATIONS S
    CROSS JOIN MONTHS M
    LEFT JOIN MART.POWER_STATION_MONTH P
        ON P.STATION_ID = S.STATION_ID
       AND P.LOCAL_MONTH = M.LOCAL_MONTH
)
SELECT
    LOCAL_MONTH,
    COUNT_IF(OBSERVED_UTC_HOURS > 0) AS STATIONS_WITH_OBSERVATIONS,
    COUNT(*) - COUNT_IF(OBSERVED_UTC_HOURS > 0) AS STATIONS_WITHOUT_OBSERVATIONS,
    AVG(CALENDAR_HOUR_OBSERVATION_PCT) AS MEAN_STATION_HOUR_COVERAGE_PCT,
    MEDIAN(CALENDAR_HOUR_OBSERVATION_PCT) AS MEDIAN_STATION_HOUR_COVERAGE_PCT,
    COUNT(*) AS STATION_POPULATION
FROM STATION_MONTH_GRID
GROUP BY LOCAL_MONTH
ORDER BY LOCAL_MONTH;
