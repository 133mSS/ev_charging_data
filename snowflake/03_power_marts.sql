-- Heavy query step: run once after full Static data is loaded.
-- Uses only the selected JPL Power analysis window to keep dashboard queries small.
USE DATABASE JPL_ANALYTICS;
USE WAREHOUSE JPL_ETL_WH;

CREATE OR REPLACE TABLE MART.SESSION_LAST_CURRENT AS
SELECT
    M.API_SESSION_ID AS SESSION_ID,
    S.STATION_ID,
    MAX(IFF(S.CHARGING_CURRENT_A > 0, S.TIMESTAMP_UTC, NULL)) AS LAST_NONZERO_CURRENT_UTC,
    COUNT(*) AS STATIC_SAMPLE_COUNT,
    COUNT_IF(S.CHARGING_CURRENT_A > 0) AS POSITIVE_CURRENT_SAMPLE_COUNT
FROM RAW.STG_STATIC_MEASUREMENTS S
JOIN RAW.STG_SESSION_MAPPING M
    ON M.STATIC_SESSION_ID = S.SESSION_ID
   AND M.MATCH_STATUS = 'MATCHED'
WHERE M.API_SESSION_ID IS NOT NULL
GROUP BY M.API_SESSION_ID, S.STATION_ID;

CREATE OR REPLACE VIEW MART.SESSION_POST_CURRENT AS
SELECT
    F.SESSION_ID,
    F.STATION_ID,
    F.LOCAL_DATE,
    F.ENERGY_KWH,
    L.LAST_NONZERO_CURRENT_UTC,
    F.DISCONNECT_TIME_UTC,
    DATEDIFF(SECOND, L.LAST_NONZERO_CURRENT_UTC, F.DISCONNECT_TIME_UTC) / 60.0
        AS POST_LAST_CURRENT_MINUTES,
    L.STATIC_SAMPLE_COUNT,
    L.POSITIVE_CURRENT_SAMPLE_COUNT
FROM WAREHOUSE.FACT_CHARGING_SESSIONS F
JOIN MART.SESSION_LAST_CURRENT L
    ON L.SESSION_ID = F.SESSION_ID
WHERE L.LAST_NONZERO_CURRENT_UTC IS NOT NULL
  AND L.LAST_NONZERO_CURRENT_UTC <= F.DISCONNECT_TIME_UTC
  AND F.DISCONNECT_TIME_UTC >= F.CONNECTION_TIME_UTC;

-- EVSE x UTC-hour. This is a station-hour sample summary, not synchronized site load.
CREATE OR REPLACE TABLE MART.POWER_STATION_HOUR AS
WITH BASE AS (
    SELECT
        STATION_ID,
        CONVERT_TIMEZONE('UTC', TIMESTAMP_UTC)::TIMESTAMP_NTZ AS UTC_TS,
        CONVERT_TIMEZONE('America/Los_Angeles', TIMESTAMP_UTC)::TIMESTAMP_NTZ AS LOCAL_TS,
        POWER_KW
    FROM WAREHOUSE.FACT_STATIC_MEASUREMENTS
    WHERE TO_DATE(CONVERT_TIMEZONE('America/Los_Angeles', TIMESTAMP_UTC)) >= '2020-07-01'::DATE
      AND TO_DATE(CONVERT_TIMEZONE('America/Los_Angeles', TIMESTAMP_UTC)) < '2020-12-01'::DATE
)
SELECT
    STATION_ID,
    DATE_TRUNC('HOUR', UTC_TS) AS UTC_HOUR_START,
    DATE_TRUNC('HOUR', LOCAL_TS) AS LOCAL_HOUR_START,
    TO_DATE(LOCAL_TS) AS LOCAL_DATE,
    DATE_TRUNC('MONTH', LOCAL_TS)::DATE AS LOCAL_MONTH,
    HOUR(LOCAL_TS) AS LOCAL_HOUR,
    COUNT(*) AS TOTAL_SAMPLES,
    COUNT(POWER_KW) AS POWER_SAMPLES,
    AVG(POWER_KW) AS AVG_POWER_KW,
    PERCENTILE_CONT(0.95) WITHIN GROUP (ORDER BY POWER_KW) AS P95_POWER_KW,
    MAX(POWER_KW) AS MAX_POWER_KW
FROM BASE
GROUP BY
    STATION_ID,
    DATE_TRUNC('HOUR', UTC_TS),
    DATE_TRUNC('HOUR', LOCAL_TS),
    TO_DATE(LOCAL_TS),
    DATE_TRUNC('MONTH', LOCAL_TS)::DATE,
    HOUR(LOCAL_TS);

CREATE OR REPLACE TABLE MART.POWER_STATION_MONTH AS
WITH MONTHLY AS (
    SELECT
        STATION_ID,
        LOCAL_MONTH,
        COUNT(DISTINCT UTC_HOUR_START) AS OBSERVED_UTC_HOURS,
        SUM(TOTAL_SAMPLES) AS TOTAL_SAMPLES,
        SUM(POWER_SAMPLES) AS POWER_SAMPLES,
        AVG(AVG_POWER_KW) AS MEAN_STATION_HOUR_POWER_KW,
        PERCENTILE_CONT(0.95) WITHIN GROUP (ORDER BY AVG_POWER_KW) AS P95_STATION_HOUR_POWER_KW
    FROM MART.POWER_STATION_HOUR
    GROUP BY STATION_ID, LOCAL_MONTH
)
SELECT
    STATION_ID,
    LOCAL_MONTH,
    OBSERVED_UTC_HOURS,
    DATEDIFF(
        HOUR,
        CONVERT_TIMEZONE('America/Los_Angeles','UTC', LOCAL_MONTH::TIMESTAMP_NTZ),
        CONVERT_TIMEZONE('America/Los_Angeles','UTC', DATEADD(MONTH, 1, LOCAL_MONTH)::TIMESTAMP_NTZ)
    ) AS EXPECTED_UTC_HOURS,
    100.0 * OBSERVED_UTC_HOURS / NULLIF(
        DATEDIFF(
            HOUR,
            CONVERT_TIMEZONE('America/Los_Angeles','UTC', LOCAL_MONTH::TIMESTAMP_NTZ),
            CONVERT_TIMEZONE('America/Los_Angeles','UTC', DATEADD(MONTH, 1, LOCAL_MONTH)::TIMESTAMP_NTZ)
        ), 0
    ) AS CALENDAR_HOUR_OBSERVATION_PCT,
    TOTAL_SAMPLES,
    POWER_SAMPLES,
    100.0 * POWER_SAMPLES / NULLIF(TOTAL_SAMPLES, 0) AS POWER_ROW_COVERAGE_PCT,
    MEAN_STATION_HOUR_POWER_KW,
    P95_STATION_HOUR_POWER_KW
FROM MONTHLY;

CREATE OR REPLACE TABLE MART.POWER_SITE_HOUR AS
WITH BOUNDS AS (
    SELECT
        CONVERT_TIMEZONE('America/Los_Angeles','UTC','2020-07-01 00:00:00'::TIMESTAMP_NTZ) AS START_UTC,
        CONVERT_TIMEZONE('America/Los_Angeles','UTC','2020-12-01 00:00:00'::TIMESTAMP_NTZ) AS END_UTC
),
HOUR_OFFSETS AS (
    SELECT ROW_NUMBER() OVER (ORDER BY SEQ4()) - 1 AS HOUR_OFFSET
    FROM TABLE(GENERATOR(ROWCOUNT => 4000))
),
HOURS AS (
    SELECT DATEADD(HOUR, O.HOUR_OFFSET, B.START_UTC) AS UTC_HOUR_START
    FROM BOUNDS B
    CROSS JOIN HOUR_OFFSETS O
    WHERE DATEADD(HOUR, O.HOUR_OFFSET, B.START_UTC) < B.END_UTC
),
STATION_SCOPE AS (
    SELECT COUNT(DISTINCT STATION_ID) AS SELECTED_STATION_COUNT
    FROM MART.POWER_STATION_HOUR
),
AGG AS (
    SELECT
        UTC_HOUR_START,
        COUNT(DISTINCT STATION_ID) AS STATIONS_WITH_ANY_SAMPLES,
        COUNT(DISTINCT IFF(POWER_SAMPLES > 0, STATION_ID, NULL)) AS STATIONS_WITH_POWER,
        SUM(TOTAL_SAMPLES) AS TOTAL_SAMPLES,
        SUM(POWER_SAMPLES) AS POWER_SAMPLES,
        SUM(AVG_POWER_KW) AS SUM_STATION_HOUR_MEAN_POWER_KW,
        AVG(AVG_POWER_KW) AS MEAN_STATION_HOUR_MEAN_POWER_KW
    FROM MART.POWER_STATION_HOUR
    GROUP BY UTC_HOUR_START
)
SELECT
    H.UTC_HOUR_START,
    CONVERT_TIMEZONE('UTC', 'America/Los_Angeles', H.UTC_HOUR_START) AS LOCAL_HOUR_START,
    TO_DATE(CONVERT_TIMEZONE('UTC', 'America/Los_Angeles', H.UTC_HOUR_START)) AS LOCAL_DATE,
    HOUR(CONVERT_TIMEZONE('UTC', 'America/Los_Angeles', H.UTC_HOUR_START)) AS LOCAL_HOUR,
    COALESCE(A.STATIONS_WITH_ANY_SAMPLES, 0) AS STATIONS_WITH_ANY_SAMPLES,
    COALESCE(A.STATIONS_WITH_POWER, 0) AS STATIONS_WITH_POWER,
    S.SELECTED_STATION_COUNT,
    100.0 * COALESCE(A.STATIONS_WITH_POWER, 0)
        / NULLIF(S.SELECTED_STATION_COUNT, 0) AS SELECTED_STATION_POWER_COVERAGE_PCT,
    COALESCE(A.TOTAL_SAMPLES, 0) AS TOTAL_SAMPLES,
    COALESCE(A.POWER_SAMPLES, 0) AS POWER_SAMPLES,
    A.SUM_STATION_HOUR_MEAN_POWER_KW,
    A.MEAN_STATION_HOUR_MEAN_POWER_KW,
    COALESCE(A.STATIONS_WITH_ANY_SAMPLES, 0) > 0 AS SITE_HOUR_HAS_ANY_OBSERVATION
FROM HOURS H
CROSS JOIN STATION_SCOPE S
LEFT JOIN AGG A USING (UTC_HOUR_START);

CREATE OR REPLACE TABLE MART.POWER_HOUR_OF_DAY_PROFILE AS
SELECT
    LOCAL_HOUR,
    AVG(AVG_POWER_KW) AS MEAN_STATION_HOUR_POWER_KW,
    PERCENTILE_CONT(0.95) WITHIN GROUP (ORDER BY AVG_POWER_KW) AS P95_STATION_HOUR_POWER_KW,
    COUNT(*) AS STATION_HOUR_OBSERVATIONS,
    COUNT(DISTINCT STATION_ID) AS STATIONS_OBSERVED,
    SUM(POWER_SAMPLES) AS POWER_SAMPLES,
    SUM(TOTAL_SAMPLES) AS TOTAL_SAMPLES
FROM MART.POWER_STATION_HOUR
WHERE POWER_SAMPLES > 0
GROUP BY LOCAL_HOUR
ORDER BY LOCAL_HOUR;

-- Fast validation views for the dashboard and report.
CREATE OR REPLACE VIEW ANALYTICS.V_Q1_WEEKDAY_HOUR AS
SELECT
    DAY_OF_WEEK,
    DAYNAME(LOCAL_DATE) AS DAY_NAME,
    LOCAL_HOUR,
    COUNT(*) AS SESSION_COUNT,
    SUM(ENERGY_KWH) AS ENERGY_KWH
FROM WAREHOUSE.FACT_CHARGING_SESSIONS
GROUP BY DAY_OF_WEEK, DAYNAME(LOCAL_DATE), LOCAL_HOUR;

CREATE OR REPLACE VIEW ANALYTICS.V_Q2_STATION_USAGE AS
SELECT
    STATION_ID,
    COUNT(*) AS SESSION_COUNT,
    SUM(ENERGY_KWH) AS TOTAL_ENERGY_KWH,
    AVG(ENERGY_KWH) AS AVG_ENERGY_PER_SESSION_KWH,
    AVG(CONNECTION_DURATION_MINUTES) AS AVG_CONNECTION_MINUTES
FROM WAREHOUSE.FACT_CHARGING_SESSIONS
GROUP BY STATION_ID;
