-- JPL warehouse layer. Run after RAW staging tables have been loaded.
USE DATABASE JPL_ANALYTICS;
USE WAREHOUSE JPL_ETL_WH;

CREATE OR REPLACE TABLE WAREHOUSE.DIM_STATION AS
SELECT
    STATION_ID,
    MAX(SPACE_ID) AS SPACE_ID,
    MAX(SITE_ID) AS SITE_ID,
    MAX(CLUSTER_ID) AS CLUSTER_ID
FROM (
    SELECT STATION_ID, SPACE_ID, SITE_ID, CLUSTER_ID
    FROM RAW.STG_CHARGING_SESSIONS
    UNION ALL
    SELECT STATION_ID, NULL, SITE_ID, NULL
    FROM RAW.STG_STATIC_MEASUREMENTS
)
WHERE STATION_ID IS NOT NULL
GROUP BY STATION_ID;

-- Conform user IDs from both API surfaces. Session IDs may be zero-padded
-- while userInputs IDs are not; keep one canonical key without discarding source IDs.
CREATE OR REPLACE TABLE WAREHOUSE.DIM_USER AS
WITH USER_ID_SOURCES AS (
    SELECT USER_ID
    FROM RAW.STG_CHARGING_SESSIONS
    WHERE USER_ID IS NOT NULL
    UNION ALL
    SELECT USER_ID
    FROM RAW.STG_USER_INPUTS
    WHERE USER_ID IS NOT NULL
),
NORMALIZED_USER_IDS AS (
    SELECT
        USER_ID,
        CASE
            WHEN USER_ID IS NULL THEN NULL
            WHEN TRIM(TO_VARCHAR(USER_ID)) = '' THEN NULL
            WHEN REGEXP_LIKE(TRIM(TO_VARCHAR(USER_ID)), '^[0-9]+')
                THEN COALESCE(NULLIF(LTRIM(TRIM(TO_VARCHAR(USER_ID)), '0'), ''), '0')
            ELSE TRIM(TO_VARCHAR(USER_ID))
        END AS USER_ID_KEY
    FROM USER_ID_SOURCES
)
SELECT
    MIN(USER_ID) AS USER_ID,
    USER_ID_KEY
FROM NORMALIZED_USER_IDS
WHERE USER_ID_KEY IS NOT NULL
GROUP BY USER_ID_KEY;

CREATE OR REPLACE TABLE WAREHOUSE.DIM_DATE AS
WITH BOUNDS AS (
    SELECT
        MIN(TO_DATE(CONVERT_TIMEZONE('America/Los_Angeles', CONNECTION_TIME))) AS MIN_DATE,
        MAX(TO_DATE(CONVERT_TIMEZONE('America/Los_Angeles', DISCONNECT_TIME))) AS MAX_DATE
    FROM RAW.STG_CHARGING_SESSIONS
),
OFFSETS AS (
    SELECT ROW_NUMBER() OVER (ORDER BY SEQ4()) - 1 AS DAY_OFFSET
    FROM TABLE(GENERATOR(ROWCOUNT => 5000))
),
CALENDAR AS (
    SELECT DATEADD(DAY, O.DAY_OFFSET, B.MIN_DATE)::DATE AS FULL_DATE
    FROM BOUNDS B
    CROSS JOIN OFFSETS O
    WHERE DATEADD(DAY, O.DAY_OFFSET, B.MIN_DATE)::DATE <= B.MAX_DATE
)
SELECT
    TO_NUMBER(TO_CHAR(FULL_DATE, 'YYYYMMDD')) AS DATE_KEY,
    FULL_DATE,
    DAY(FULL_DATE) AS DAY,
    DAYOFWEEKISO(FULL_DATE) AS DAY_OF_WEEK,
    DAYNAME(FULL_DATE) AS DAY_NAME,
    WEEKOFYEAR(FULL_DATE) AS WEEK_OF_YEAR,
    MONTH(FULL_DATE) AS MONTH,
    MONTHNAME(FULL_DATE) AS MONTH_NAME,
    QUARTER(FULL_DATE) AS QUARTER,
    YEAR(FULL_DATE) AS YEAR
FROM CALENDAR;

CREATE OR REPLACE TABLE WAREHOUSE.DIM_TIME AS
WITH MINUTES AS (
    SELECT ROW_NUMBER() OVER (ORDER BY SEQ4()) - 1 AS MINUTE_OF_DAY
    FROM TABLE(GENERATOR(ROWCOUNT => 1440))
)
SELECT
    MINUTE_OF_DAY AS TIME_KEY,
    TO_TIME(DATEADD(MINUTE, MINUTE_OF_DAY, '2000-01-01'::TIMESTAMP_NTZ)) AS FULL_TIME,
    FLOOR(MINUTE_OF_DAY / 60) AS HOUR,
    MOD(MINUTE_OF_DAY, 60) AS MINUTE,
    CASE
        WHEN FLOOR(MINUTE_OF_DAY / 60) < 6 THEN 'Night'
        WHEN FLOOR(MINUTE_OF_DAY / 60) < 12 THEN 'Morning'
        WHEN FLOOR(MINUTE_OF_DAY / 60) < 18 THEN 'Afternoon'
        ELSE 'Evening'
    END AS TIME_OF_DAY
FROM MINUTES;

CREATE OR REPLACE TABLE WAREHOUSE.FACT_CHARGING_SESSIONS AS
SELECT
    SESSION_ID,
    USER_ID,
    CASE
        WHEN USER_ID IS NULL THEN NULL
        WHEN TRIM(TO_VARCHAR(USER_ID)) = '' THEN NULL
        WHEN REGEXP_LIKE(TRIM(TO_VARCHAR(USER_ID)), '^[0-9]+')
            THEN COALESCE(NULLIF(LTRIM(TRIM(TO_VARCHAR(USER_ID)), '0'), ''), '0')
        ELSE TRIM(TO_VARCHAR(USER_ID))
    END AS USER_ID_KEY,
    STATION_ID,
    SITE_ID,
    SPACE_ID,
    CLUSTER_ID,
    CONNECTION_TIME AS CONNECTION_TIME_UTC,
    DISCONNECT_TIME AS DISCONNECT_TIME_UTC,
    DONE_CHARGING_TIME AS DONE_CHARGING_TIME_API_UTC,
    CONVERT_TIMEZONE('America/Los_Angeles', CONNECTION_TIME) AS CONNECTION_TIME_LOCAL,
    CONVERT_TIMEZONE('America/Los_Angeles', DISCONNECT_TIME) AS DISCONNECT_TIME_LOCAL,
    TO_NUMBER(TO_CHAR(
        TO_DATE(CONVERT_TIMEZONE('America/Los_Angeles', CONNECTION_TIME)),
        'YYYYMMDD'
    )) AS DATE_KEY,
    (
        HOUR(CONVERT_TIMEZONE('America/Los_Angeles', CONNECTION_TIME)) * 60
        + MINUTE(CONVERT_TIMEZONE('America/Los_Angeles', CONNECTION_TIME))
    ) AS TIME_KEY,
    TO_DATE(CONVERT_TIMEZONE('America/Los_Angeles', CONNECTION_TIME)) AS LOCAL_DATE,
    HOUR(CONVERT_TIMEZONE('America/Los_Angeles', CONNECTION_TIME)) AS LOCAL_HOUR,
    DAYOFWEEKISO(TO_DATE(CONVERT_TIMEZONE('America/Los_Angeles', CONNECTION_TIME))) AS DAY_OF_WEEK,
    ENERGY_KWH,
    TIMEZONE,
    HAS_USER_METADATA,
    CONNECTION_DURATION_MINUTES,
    DONE_AFTER_DISCONNECT
FROM RAW.STG_CHARGING_SESSIONS
WHERE SESSION_ID IS NOT NULL;

