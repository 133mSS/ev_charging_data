-- JPL warehouse layer. Run after RAW staging tables have been loaded.
USE DATABASE JPL_ANALYTICS;
USE WAREHOUSE JPL_ETL_WH;

CREATE OR REPLACE TABLE WAREHOUSE.DIM_STATION AS
SELECT
    STATION_ID,
    MAX(SPACE_ID) AS SPACE_ID,
    MAX(SITE_ID) AS SITE_ID,
    MAX(CLUSTER_ID) AS CLUSTER_ID
FROM (
    SELECT STATION_ID, SPACE_ID, SITE_ID, CLUSTER_ID
    FROM RAW.STG_CHARGING_SESSIONS
    UNION ALL
    SELECT STATION_ID, NULL, SITE_ID, NULL
    FROM RAW.STG_STATIC_MEASUREMENTS
)
WHERE STATION_ID IS NOT NULL
GROUP BY STATION_ID;

CREATE OR REPLACE TABLE WAREHOUSE.DIM_USER AS
SELECT DISTINCT USER_ID
FROM RAW.STG_CHARGING_SESSIONS
WHERE USER_ID IS NOT NULL;

CREATE OR REPLACE TABLE WAREHOUSE.DIM_DATE AS
WITH BOUNDS AS (
    SELECT
        MIN(TO_DATE(CONVERT_TIMEZONE('UTC','America/Los_Angeles', CONNECTION_TIME::TIMESTAMP_NTZ))) AS MIN_DATE,
        MAX(TO_DATE(CONVERT_TIMEZONE('UTC','America/Los_Angeles', DISCONNECT_TIME::TIMESTAMP_NTZ))) AS MAX_DATE
    FROM RAW.STG_CHARGING_SESSIONS
),
CALENDAR AS (
    SELECT DATEADD(DAY, SEQ4(), MIN_DATE)::DATE AS FULL_DATE
    FROM BOUNDS, TABLE(GENERATOR(ROWCOUNT => 5000))
    WHERE DATEADD(DAY, SEQ4(), MIN_DATE)::DATE <= MAX_DATE
)
SELECT
    TO_NUMBER(TO_CHAR(FULL_DATE, 'YYYYMMDD')) AS DATE_KEY,
    FULL_DATE,
    DAY(FULL_DATE) AS DAY,
    DAYOFWEEKISO(FULL_DATE) AS DAY_OF_WEEK,
    DAYNAME(FULL_DATE) AS DAY_NAME,
    WEEKOFYEAR(FULL_DATE) AS WEEK_OF_YEAR,
    MONTH(FULL_DATE) AS MONTH,
    MONTHNAME(FULL_DATE) AS MONTH_NAME,
    QUARTER(FULL_DATE) AS QUARTER,
    YEAR(FULL_DATE) AS YEAR
FROM CALENDAR;

CREATE OR REPLACE TABLE WAREHOUSE.DIM_TIME AS
WITH MINUTES AS (
    SELECT SEQ4() AS MINUTE_OF_DAY
    FROM TABLE(GENERATOR(ROWCOUNT => 1440))
)
SELECT
    MINUTE_OF_DAY AS TIME_KEY,
    TO_TIME(DATEADD(MINUTE, MINUTE_OF_DAY, '2000-01-01'::TIMESTAMP_NTZ)) AS FULL_TIME,
    FLOOR(MINUTE_OF_DAY / 60) AS HOUR,
    MOD(MINUTE_OF_DAY, 60) AS MINUTE,
    CASE
        WHEN FLOOR(MINUTE_OF_DAY / 60) < 6 THEN 'Night'
        WHEN FLOOR(MINUTE_OF_DAY / 60) < 12 THEN 'Morning'
        WHEN FLOOR(MINUTE_OF_DAY / 60) < 18 THEN 'Afternoon'
        ELSE 'Evening'
    END AS TIME_OF_DAY
FROM MINUTES;

CREATE OR REPLACE TABLE WAREHOUSE.FACT_CHARGING_SESSIONS AS
SELECT
    SESSION_ID,
    USER_ID,
    STATION_ID,
    SITE_ID,
    SPACE_ID,
    CLUSTER_ID,
    CONNECTION_TIME AS CONNECTION_TIME_UTC,
    DISCONNECT_TIME AS DISCONNECT_TIME_UTC,
    DONE_CHARGING_TIME AS DONE_CHARGING_TIME_API_UTC,
    CONVERT_TIMEZONE('UTC','America/Los_Angeles', CONNECTION_TIME::TIMESTAMP_NTZ) AS CONNECTION_TIME_LOCAL,
    CONVERT_TIMEZONE('UTC','America/Los_Angeles', DISCONNECT_TIME::TIMESTAMP_NTZ) AS DISCONNECT_TIME_LOCAL,
    TO_DATE(CONVERT_TIMEZONE('UTC','America/Los_Angeles', CONNECTION_TIME::TIMESTAMP_NTZ)) AS LOCAL_DATE,
    HOUR(CONVERT_TIMEZONE('UTC','America/Los_Angeles', CONNECTION_TIME::TIMESTAMP_NTZ)) AS LOCAL_HOUR,
    DAYOFWEEKISO(TO_DATE(CONVERT_TIMEZONE('UTC','America/Los_Angeles', CONNECTION_TIME::TIMESTAMP_NTZ))) AS DAY_OF_WEEK,
    ENERGY_KWH,
    TIMEZONE,
    HAS_USER_METADATA,
    CONNECTION_DURATION_MINUTES,
    DONE_AFTER_DISCONNECT
FROM RAW.STG_CHARGING_SESSIONS
WHERE SESSION_ID IS NOT NULL;

CREATE OR REPLACE TABLE WAREHOUSE.FACT_USER_REQUESTS AS
SELECT
    SESSION_ID,
    INPUT_ID,
    USER_ID,
    MILES_REQUESTED,
    WH_PER_MILE,
    MINUTES_AVAILABLE,
    MODIFIED_AT,
    PAYMENT_REQUIRED,
    REQUESTED_DEPARTURE,
    KWH_REQUESTED,
    DEPARTURE_BEFORE_MODIFIED,
    TO_DATE(CONVERT_TIMEZONE('UTC','America/Los_Angeles', MODIFIED_AT::TIMESTAMP_NTZ)) AS LOCAL_MODIFIED_DATE,
    HOUR(CONVERT_TIMEZONE('UTC','America/Los_Angeles', MODIFIED_AT::TIMESTAMP_NTZ)) AS LOCAL_MODIFIED_HOUR
FROM RAW.STG_USER_INPUTS
WHERE SESSION_ID IS NOT NULL;

-- This view retains ALL Static measurements, including STATIC_ONLY sessions.
-- API session fields are nullable by design.
CREATE OR REPLACE VIEW WAREHOUSE.FACT_STATIC_MEASUREMENTS AS
SELECT
    S.SITE_ID,
    S.STATION_ID,
    S.SESSION_ID AS STATIC_SESSION_ID,
    M.API_SESSION_ID,
    COALESCE(M.MATCH_STATUS, 'UNMAPPED_STATIC') AS MATCH_STATUS,
    S.TIMESTAMP_UTC,
    CONVERT_TIMEZONE('UTC','America/Los_Angeles', S.TIMESTAMP_UTC::TIMESTAMP_NTZ) AS TIMESTAMP_LOCAL,
    S.CHARGING_CURRENT_A,
    S.ACTUAL_PILOT_A,
    S.VOLTAGE_V,
    S.CHARGING_STATE,
    S.ENERGY_DELIVERED_KWH,
    S.POWER_KW
FROM RAW.STG_STATIC_MEASUREMENTS S
LEFT JOIN RAW.STG_SESSION_MAPPING M
    ON M.STATIC_SESSION_ID = S.SESSION_ID;

-- Basic row-count and population snapshot for reproducible report evidence.
CREATE OR REPLACE VIEW MART.V_LOAD_RECONCILIATION AS
SELECT 'API_SESSIONS' AS DATASET, COUNT(*) AS ROW_COUNT FROM WAREHOUSE.FACT_CHARGING_SESSIONS
UNION ALL
SELECT 'USER_INPUTS', COUNT(*) FROM WAREHOUSE.FACT_USER_REQUESTS
UNION ALL
SELECT 'STATIC_MEASUREMENTS_ALL', COUNT(*) FROM WAREHOUSE.FACT_STATIC_MEASUREMENTS
UNION ALL
SELECT 'STATIC_SESSIONS_ALL', COUNT(DISTINCT STATIC_SESSION_ID) FROM WAREHOUSE.FACT_STATIC_MEASUREMENTS
UNION ALL
SELECT 'STATIC_SESSIONS_MATCHED', COUNT(DISTINCT STATIC_SESSION_ID) FROM WAREHOUSE.FACT_STATIC_MEASUREMENTS WHERE MATCH_STATUS = 'MATCHED'
UNION ALL
SELECT 'STATIC_SESSIONS_ONLY', COUNT(DISTINCT STATIC_SESSION_ID) FROM WAREHOUSE.FACT_STATIC_MEASUREMENTS WHERE MATCH_STATUS = 'STATIC_ONLY';
