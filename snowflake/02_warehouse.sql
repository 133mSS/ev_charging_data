CREATE OR REPLACE TABLE WAREHOUSE.DIM_DATE AS
WITH BOUNDS AS (
    SELECT
        MIN(TO_DATE(CONVERT_TIMEZONE('America/Los_Angeles', CONNECTION_TIME))) AS MIN_DATE,
        MAX(TO_DATE(CONVERT_TIMEZONE('America/Los_Angeles', DISCONNECT_TIME))) AS MAX_DATE
    FROM RAW.STG_CHARGING_SESSIONS
),
OFFSETS AS (
    SELECT ROW_NUMBER() OVER (ORDER BY SEQ4()) - 1 AS DAY_OFFSET
    FROM TABLE(GENERATOR(ROWCOUNT => 5000))
),
CALENDAR AS (
    SELECT DATEADD(DAY, O.DAY_OFFSET, B.MIN_DATE)::DATE AS FULL_DATE
    FROM BOUNDS B
    CROSS JOIN OFFSETS O
    WHERE DATEADD(DAY, O.DAY_OFFSET, B.MIN_DATE)::DATE <= B.MAX_DATE
)
SELECT
    TO_NUMBER(TO_CHAR(FULL_DATE, 'YYYYMMDD')) AS DATE_KEY,
    FULL_DATE,
    DAY(FULL_DATE) AS DAY,
    DAYOFWEEKISO(FULL_DATE) AS DAY_OF_WEEK,
    DAYNAME(FULL_DATE) AS DAY_NAME,
    WEEKOFYEAR(FULL_DATE) AS WEEK_OF_YEAR,
    MONTH(FULL_DATE) AS MONTH,
    MONTHNAME(FULL_DATE) AS MONTH_NAME,
    QUARTER(FULL_DATE) AS QUARTER,
    YEAR(FULL_DATE) AS YEAR
FROM CALENDAR;

CREATE OR REPLACE TABLE WAREHOUSE.DIM_TIME AS
WITH MINUTES AS (
    SELECT ROW_NUMBER() OVER (ORDER BY SEQ4()) - 1 AS MINUTE_OF_DAY
    FROM TABLE(GENERATOR(ROWCOUNT => 1440))
)
SELECT
    MINUTE_OF_DAY AS TIME_KEY,
    TO_TIME(DATEADD(MINUTE, MINUTE_OF_DAY, '2000-01-01'::TIMESTAMP_NTZ)) AS FULL_TIME,
    FLOOR(MINUTE_OF_DAY / 60) AS HOUR,
    MOD(MINUTE_OF_DAY, 60) AS MINUTE,
    CASE
        WHEN FLOOR(MINUTE_OF_DAY / 60) < 6 THEN 'Night'
        WHEN FLOOR(MINUTE_OF_DAY / 60) < 12 THEN 'Morning'
        WHEN FLOOR(MINUTE_OF_DAY / 60) < 18 THEN 'Afternoon'
        ELSE 'Evening'
    END AS TIME_OF_DAY
FROM MINUTES;

