-- JPL EV Charging Analytics: Snowflake bootstrap
-- Safe to re-run. Uses a small auto-suspending warehouse to protect trial credits.

CREATE DATABASE IF NOT EXISTS JPL_ANALYTICS;

CREATE SCHEMA IF NOT EXISTS JPL_ANALYTICS.RAW;
CREATE SCHEMA IF NOT EXISTS JPL_ANALYTICS.STAGING;
CREATE SCHEMA IF NOT EXISTS JPL_ANALYTICS.WAREHOUSE;
CREATE SCHEMA IF NOT EXISTS JPL_ANALYTICS.MART;
CREATE SCHEMA IF NOT EXISTS JPL_ANALYTICS.ANALYTICS;

CREATE WAREHOUSE IF NOT EXISTS JPL_ETL_WH
    WAREHOUSE_SIZE = 'XSMALL'
    AUTO_SUSPEND = 60
    AUTO_RESUME = TRUE
    INITIALLY_SUSPENDED = TRUE
    COMMENT = 'JPL EV Charging Analytics ETL and analytics warehouse';

USE WAREHOUSE JPL_ETL_WH;
USE DATABASE JPL_ANALYTICS;

CREATE FILE FORMAT IF NOT EXISTS RAW.JPL_CSV_GZ_FORMAT
    TYPE = CSV
    COMPRESSION = AUTO
    SKIP_HEADER = 1
    FIELD_OPTIONALLY_ENCLOSED_BY = '"'
    EMPTY_FIELD_AS_NULL = TRUE
    NULL_IF = ('', 'NULL', 'null', 'NaN', 'nan')
    ERROR_ON_COLUMN_COUNT_MISMATCH = TRUE
    TRIM_SPACE = TRUE;

CREATE STAGE IF NOT EXISTS RAW.JPL_RAW_STAGE
    FILE_FORMAT = RAW.JPL_CSV_GZ_FORMAT
    COMMENT = 'Raw, cleaned JPL ACN-Data CSV and CSV.GZ landing stage';
