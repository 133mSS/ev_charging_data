-- JPL RAW landing tables. Types are deliberately permissive enough for ACN CSV.
USE DATABASE JPL_ANALYTICS;
USE SCHEMA RAW;

CREATE TABLE IF NOT EXISTS STG_CHARGING_SESSIONS (
    RECORD_ID VARCHAR,
    SESSION_ID VARCHAR,
    USER_ID VARCHAR,
    STATION_ID VARCHAR,
    SPACE_ID VARCHAR,
    SITE_ID VARCHAR,
    CLUSTER_ID VARCHAR,
    CONNECTION_TIME TIMESTAMP_TZ,
    DISCONNECT_TIME TIMESTAMP_TZ,
    DONE_CHARGING_TIME TIMESTAMP_TZ,
    ENERGY_KWH NUMBER(18,6),
    TIMEZONE VARCHAR,
    HAS_USER_METADATA BOOLEAN,
    CONNECTION_DURATION_MINUTES NUMBER(18,6),
    DONE_AFTER_DISCONNECT BOOLEAN
);

CREATE TABLE IF NOT EXISTS STG_USER_INPUTS (
    SESSION_ID VARCHAR,
    INPUT_ID NUMBER(12,0),
    USER_ID VARCHAR,
    MILES_REQUESTED NUMBER(18,6),
    WH_PER_MILE NUMBER(18,6),
    MINUTES_AVAILABLE NUMBER(18,6),
    MODIFIED_AT TIMESTAMP_TZ,
    PAYMENT_REQUIRED BOOLEAN,
    REQUESTED_DEPARTURE TIMESTAMP_TZ,
    KWH_REQUESTED NUMBER(18,6),
    DEPARTURE_BEFORE_MODIFIED BOOLEAN
);

CREATE TABLE IF NOT EXISTS STG_STATIC_MEASUREMENTS (
    SITE_ID VARCHAR,
    STATION_ID VARCHAR,
    SESSION_ID VARCHAR,
    TIMESTAMP_UTC TIMESTAMP_TZ,
    CHARGING_CURRENT_A FLOAT,
    ACTUAL_PILOT_A FLOAT,
    VOLTAGE_V FLOAT,
    CHARGING_STATE VARCHAR,
    ENERGY_DELIVERED_KWH FLOAT,
    POWER_KW FLOAT
);

CREATE TABLE IF NOT EXISTS STG_SESSION_MAPPING (
    STATION_ID VARCHAR,
    STATIC_SESSION_ID VARCHAR,
    API_SESSION_ID VARCHAR,
    MATCH_STATUS VARCHAR
);

CREATE TABLE IF NOT EXISTS LOAD_AUDIT (
    LOAD_ID NUMBER AUTOINCREMENT START 1 INCREMENT 1,
    SOURCE_FILE VARCHAR,
    TARGET_TABLE VARCHAR,
    ROWS_LOADED NUMBER,
    LOADED_AT TIMESTAMP_TZ DEFAULT CURRENT_TIMESTAMP(),
    STATUS VARCHAR,
    DETAILS VARCHAR
);
